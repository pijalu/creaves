// buildSeedMatcher materializes one seed matcher model (expression parse
// checked by Validate at save time).
func buildSeedMatcher(def seedMatcherDef) *models.CareMatcher {
	return &models.CareMatcher{
		Name:        def.Name,
		Description: nulls.NewString(fmt.Sprintf("Bibliothèque §7.4 %s [source: %s]", def.Key, ConverterTag)),
		Expression:  def.Expression,
	}
}

// buildSeedRule materializes one seed rule model. caretypeID resolved by
// the caller; feeding-kind seeds ship active (§8.1 step 1), everything
// else is an inactive draft for admin review.
func buildSeedRule(def seedRuleDef, matcherID uuid.NullUUID, caretypeID string) (*models.CareRule, error) {
	// R8-3: SR13 ENFORCES cleanup on flagged zones — it ships active (the
	// whole point of the rule); everything else stays an inactive draft.
	active := def.Kind == careplan.KindFeeding || def.Key == "SR13"
	r := &models.CareRule{
		Name:            def.Name,
		Description:     nulls.NewString(fmt.Sprintf("Bibliothèque §7.4 %s [source: %s]", def.Key, ConverterTag)),
		ActionKind:      def.Kind,
		ActionPayload:   buildSeedPayload(def, caretypeID),
		Schedule:        []byte(def.ScheduleJSON),
		MatcherID:       matcherID,
		Active:          active,
		StopOnOuttake:   true,
		LatchMembership: def.DurationDays > 0,
	}
	if verrs, err := r.Validate(nil); verrs.HasAny() || err != nil {
		return nil, fmt.Errorf("seed %s invalid: %v / %v", def.Key, verrs, err)
	}
	return r, nil
}

func buildSeedPayload(def seedRuleDef, caretypeID string) []byte {
	switch def.Kind {
	case careplan.KindFeeding:
		return []byte(marshalSeed(map[string]any{
			"caretype_id": caretypeID, "food": def.PayloadFood, "force_feed": def.ForceFeed, "note": def.Note,
		}))
	case careplan.KindMedication:
		m := map[string]any{"drug": def.Drug, "note": def.Note}
		if def.DosageTable {
			m["dosage_from_dosages_table"] = true
		} else {
			m["dosage"] = def.Dosage
		}
		return []byte(marshalSeed(m))
	case careplan.KindCare:
		return []byte(marshalSeed(map[string]any{
			"caretype_id": caretypeID, "instructions": def.Instructions, "note": def.Note,
		}))
	default: // cleanup / weighing: no required fields
		return []byte(marshalSeed(map[string]any{"note": def.Note}))
	}
}

func marshalSeed(m map[string]any) []byte {
	// encoding/json sorts map keys — deterministic output.
	b, err := json.Marshal(m)
	if err != nil {
		return []byte("{}")
	}
	return b
}
