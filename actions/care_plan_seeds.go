// §7.4 seed library of docs/care-expert.md: 13 canonical matchers (SM1–SM13)
// and 12 rules (SR1–SR12), derived from the 2025/2026 production cohort.
// They ship as inactive drafts — except feeding-kind seeds, which ship
// active because the legacy `feeding_period` generator is frozen in the
// same boot (§8.1 step 3, no double-feed window exists).
//
// Four rules need a composite condition (SR1: SM1+weight, SR4: SM4+SM11,
// SR6: SM6+SM11, SR12: SM1 OR SM2). The care_rules schema references one
// matcher only, so each composite rule gets one derived matcher whose
// expression inlines the referenced seeds; they are clearly marked
// "(dérivé)" and are NOT part of the SM1–SM13 canonical set.

// ConverterTag marks rows generated by the startup converter so rollback
// can identify them (§8.2: "tagged created_by='care_plan_converter'").
const ConverterTag = "care_plan_converter"

// seedMatcherDef is one §7.4 seed matcher row.
type seedMatcherDef struct {
	Key        string // SM1..SM13 (or "SR1*" for derived)
	Name       string
	Expression string
	Derived    bool // true for the composite-rule matchers
}

// seedRuleDef is one §7.4 seed rule row. CaretypeName is resolved against
// the live caretypes table at conversion time; rules whose caretype is
// missing are skipped with a report line (payload needs a real id, §4.2).
type seedRuleDef struct {
	Key          string // SR1..SR12
	Name         string
	Kind         string
	MatcherKey   string // seedMatcherDef.Key
	CaretypeName string // "" = no caretype (cleanup/weighing)
	ScheduleJSON string
	PayloadFood  string
	ForceFeed    bool
	Drug         string
	Dosage       string
	DosageTable  bool
	Note         string
	Instructions string
	DurationDays int
}

